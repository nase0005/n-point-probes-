class PoissonBinomialPMF(nn.Module):
    """Computes P(R_v = r) for Poisson Binomial Distribution using dynamic programming.

    Given probabilities p of shape (batch_size, n), this computes the log-likelihood
    of observing exactly 'r' hits out of 'n' samples.
    """

    def __init__(self):
        super().__init__()

    def forward(self, p: torch.Tensor, r: torch.Tensor) -> torch.Tensor:
        """Args:

        p: Tensor of shape (B, n) containing p_v(x_j) probabilities.
        r: Tensor of shape (B,) containing observed target segment counts.

        Returns:
            log_prob: Tensor of shape (B,) containing log P(R_v = r).
        """
        B, n = p.shape

        # dp[i][j] = P(j hits using first i pixels)
        # We compute this in log-space or probability space; using DP table:
        dp = torch.zeros(B, n + 1, device=p.device, dtype=p.dtype)
        dp[:, 0] = 1.0  # Base case: 0 pixels sampled -> 0 hits with probability 1

        for i in range(n):
            p_i = p[:, i : i + 1]  # Shape (B, 1)
            dp_next = torch.zeros_like(dp)

            # 0 hits at step i+1: previous 0 hits AND pixel i is not target
            dp_next[:, 0] = dp[:, 0] * (1.0 - p_i.squeeze(-1))

            # k hits at step i+1: (k hits & not target) OR (k-1 hits & target)
            dp_next[:, 1:] = dp[:, 1:] * (1.0 - p_i) + dp[:, :-1] * p_i

            dp = dp_next

        # Gather probability corresponding to observed r for each batch item
        batch_indices = torch.arange(B, device=p.device)
        prob_r = dp[batch_indices, r]

        # Numerical stability clamp
        prob_r = torch.clamp(prob_r, min=1e-12)
        return torch.log(prob_r)


class LaplacianSmoothnessLoss(nn.Module):
    """
    Calculates the 'smoothness' of a 2D map by penalizing the 
    squared differences between adjacent pixels.
    
    Equivalent to the term x^T L x (Dirichlet energy) on a grid graph.
    """
    def __init__(self, reduction='mean'):
        super().__init__()
        self.reduction = reduction

    def forward(self, map_tensor):
        """
        Args:
            map_tensor: Input tensor of shape (Batch, Channels, Height, Width)
                        Usually the Uncertainty Map or Logits.
        """
        # 1. Compute differences between horizontal neighbors
        #    (Right pixel - Left pixel)
        diff_x = map_tensor[:, :, :, 1:] - map_tensor[:, :, :, :-1]
        
        # 2. Compute differences between vertical neighbors
        #    (Bottom pixel - Top pixel)
        diff_y = map_tensor[:, :, 1:, :] - map_tensor[:, :, :-1, :]
        
        # 3. Square the differences (L2 norm of the gradient)
        loss_x = diff_x ** 2
        loss_y = diff_y ** 2
        
        # 4. Combine and reduce
        if self.reduction == 'mean':
            return loss_x.mean() + loss_y.mean()
        elif self.reduction == 'sum':
            return loss_x.sum() + loss_y.sum()
        else:
            return loss_x, loss_y


class SpatialConcentrationLoss(nn.Module):
    """
    Penalizes the spatial variance of maps.
    Forces each map to concentrate its mass around a single centroid.
    """
    def __init__(self):
        super().__init__()

    def forward(self, maps):
        """
        Args:
            maps: (Batch, K, H, W). 
                  Should be non-negative (e.g. passed through Softmax or ReLU).
        """
        batch_size, K, H, W = maps.shape
        device = maps.device

        # 1. Create coordinate grids
        # Normalized coordinates [-1, 1] usually work better for optimization stability
        y_coords = torch.linspace(-1, 1, H, device=device).view(1, 1, H, 1)
        x_coords = torch.linspace(-1, 1, W, device=device).view(1, 1, 1, W)
        
        # Expand grids to match batch size: (B, K, H, W)
        # Note: We don't allocate new memory, just broadcast
        x_grid = x_coords.expand(batch_size, K, H, W)
        y_grid = y_coords.expand(batch_size, K, H, W)

        # 2. Normalize maps to be spatial Probability Mass Functions (sum=1)
        # Add epsilon to prevent division by zero for empty maps
        map_sums = maps.sum(dim=(2, 3), keepdim=True) + 1e-6
        spatial_probs = maps / map_sums

        # 3. Calculate Center of Mass (Expected Value of X and Y)
        # Sum over H, W
        center_x = (spatial_probs * x_grid).sum(dim=(2, 3), keepdim=True)
        center_y = (spatial_probs * y_grid).sum(dim=(2, 3), keepdim=True)

        # 4. Calculate Variance (Expected Squared Distance from Center)
        # (x - mu_x)^2 + (y - mu_y)^2
        dist_sq_x = (x_grid - center_x) ** 2
        dist_sq_y = (y_grid - center_y) ** 2
        
        # Weighted sum of squared distances
        variance = (spatial_probs * (dist_sq_x + dist_sq_y)).sum(dim=(2, 3))

        # 5. Return mean loss over the batch and K segments
        return variance.mean()


