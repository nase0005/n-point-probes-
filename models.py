class ProbabilisticSegmentation():
    def __init__(self, probability_map=None, dimensions=None, label_map = None):
        num_provided_args = sum([arg is not None for arg in [dimensions, probability_map, label_map]])
        if num_provided_args != 1:
            raise ValueError("Exactly one of 'dimensions', 'probability_map', or 'label_map' must be provided.")
        if dimensions is not None:
            self.K, self.H, self.W = dimensions
            self.probability_map = torch.ones(dimensions)/self.K 
        if probability_map is not None:
            self.check_probability_map(probability_map)
            self.K, self.H, self.W = probability_map.shape
            self.probability_map = probability_map
        if label_map is not None:
            self.probability_map = self.probability_map_from_label_map(label_map)
            self.check_probability_map()
            self.K, self.H, self.W = self.probability_map.shape

    def check_probability_map(self, probability_map=None):
        if probability_map is None:
            probability_map = self.probability_map
        if not (probability_map >= 0).all():
            raise ValueError("All values in 'probability_map' must be non-negative.")
        if not torch.isclose(probability_map.sum(dim=0), torch.ones(probability_map.shape[1], probability_map.shape[2], device = probability_map.device)).all():
            raise ValueError("The sum of probabilities along dimension 0 must be equal to 1 for each pixel.")
        else:
            print("Probability map is valid.")

    def probability_map_from_label_map(self, label_map):
        ##image dimensions
        H,W = label_map.shape
        ##find the unique labels
        unique_labels = torch.unique(label_map)
        K = len(unique_labels)
        probability_map = torch.zeros((K, H, W))
        for i,k in enumerate(unique_labels):
            probability_map[i] = (label_map == k) 
        return probability_map

    def pixel_comembership(self):
        pm = self.probability_map.flatten(1) ##K x HW
        return pm.T @ pm ##HW x HW

    def probability_map_to_string(self):
        """
        Converts a PyTorch tensor (probability map) into a portable JSON string.
        
        Args:
            tensor (Tensor): The input probability map.
            
        Returns:
            str: A JSON string containing shape, dtype, and base64-encoded data.
        """
        # 1. Move to CPU and convert to Numpy
        # We must detach if it requires grad, and move to CPU to convert to numpy
        np_array = self.probability_map.detach().cpu().numpy()
        
        # 2. Serialize the binary data
        # tobytes() gets the raw bits. b64encode converts those bits to ASCII bytes.
        # decode('utf-8') turns those ASCII bytes into a standard Python string.
        b64_data = base64.b64encode(np_array.tobytes()).decode('utf-8')
        
        # 3. Create a dictionary with necessary metadata
        # We need the dtype and shape to reconstruct it correctly later.
        payload = {
            "dtype": str(np_array.dtype),
            "shape": np_array.shape,
            "data": b64_data
        }
        
        # 4. Convert dictionary to JSON string
        return json.dumps(payload)


def dirichlet_probability_map(K, H, W, alpha=20.):
    alpha = torch.tensor([alpha]*K)
    dist = Dirichlet(alpha)
    probability_map = dist.sample((W,H)).transpose(0,2)
    return probability_map

    

def string_to_probability_map(s):
    """
    Reconstructs a PyTorch tensor from the string generated by `probability_map_to_string`.
    
    Args:
        s (str): The JSON string.
        
    Returns:
        Tensor: The reconstructed PyTorch tensor.
    """
    # 1. Parse the JSON string
    payload = json.loads(s)
    
    # 2. Extract metadata
    dtype_name = payload['dtype']
    shape = payload['shape']
    b64_data = payload['data']
    
    # 3. Decode the binary data
    # Convert string back to bytes
    raw_bytes = base64.b64decode(b64_data)
    
    # 4. Reconstruct Numpy Array
    # frombuffer interprets the raw bytes as numbers of the specified dtype
    np_array = np.frombuffer(raw_bytes, dtype=dtype_name)
    
    # 5. Reshape and Convert to Torch
    np_array = np_array.reshape(shape)
    
    # We create a copy to avoid "The given NumPy array is not writeable" warnings 
    # that can occur with read-only buffers from strings.
    tensor = torch.from_numpy(np_array.copy())
    
    return tensor    


