def objectwise_similarity(learned_map, truth_map, threshold_ratio=1.0):
    """
    Computes the object-wise cosine similarity between a learned map and a ground truth map,
    weighted by the pixel overlap between segments.
    
    Args:
        learned_map (Tensor): Shape (K_L, H, W).
        truth_map (Tensor): Shape (K_T, H, W).
        threshold_ratio (float): Multiplier for the 1/K threshold.
        
    Returns:
        similarity_scores (Tensor): Shape (K_L,). The weighted average similarity 
                                    for each learned segment.
    """
    # 1. Get Shapes and Flatten
    K_L, H, W = learned_map.shape
    K_T = truth_map.shape[0]
    
    flat_L = learned_map.reshape(K_L, -1)
    flat_T = truth_map.reshape(K_T, -1)
    
    # 2. Thresholding (Active Pixels)
    thresh_L = (1.0 / K_L) * threshold_ratio
    thresh_T = (1.0 / K_T) * threshold_ratio
    
    active_L = (flat_L > thresh_L).float()
    active_T = (flat_T > thresh_T).float()
    
    # 3. Calculate Weights (Pixel Overlap Counts)
    # Matrix Mult: (K_L, N) @ (N, K_T) -> (K_L, K_T)
    # Entry [i, j] is exactly the number of pixels shared by Learned_i and Truth_j
    weights = torch.mm(active_L, active_T.t())
    
    # 4. Compute All-Pairs Cosine Similarity
    # Normalize vectors
    norm_L = F.normalize(flat_L, p=2, dim=1)
    norm_T = F.normalize(flat_T, p=2, dim=1)
    
    # Similarity Matrix: (K_L, K_T)
    # Entry [i, j] is the cosine similarity between Learned_i and Truth_j
    similarities = torch.mm(norm_L, norm_T.t())
    
    # 5. Compute Weighted Average
    # We want: Sum(Sim_ij * Weight_ij) / Sum(Weight_ij) for each row i
    
    # Numerator: Weighted sum of similarities
    weighted_sum = (similarities * weights).sum(dim=1) # Shape (K_L,)
    
    # Denominator: Total weight (Total overlapping pixels for this learned segment)
    total_weights = weights.sum(dim=1) # Shape (K_L,)
    
    # 6. Safe Division
    # Avoid division by zero for learned segments that have NO overlap with truth
    # We set their score to 0.0
    scores = torch.zeros_like(weighted_sum)
    mask = total_weights > 0


# exponentiated gradient descent
class ExpGradient(Optimizer):
    r'''Exponentiated gradient descent optimizer.

    The class ``ExpGradient`` is a subclass of torch.Optimizer. The gradient
    step is

    .. math::

        x_i = x_i \exp\left( -\lambda \nabla L \right) \quad \text{and} 
        \quad x_i = \frac{x_i}{\sum_k x_k}
    
                
    where :math:`\lambda` is the learning rate and :math:`L` is the loss 
    function.

    Parameters
    ----------
    params : iterable
        Iterable of params to optimize or dicts defining param groups.
    lr : float
        Learning rate (default: 1e-3).


    .. Note:: 

    This implementation authored by Jonathan Vacher, 2021
    
    The exponentiated Gradient descent is introduced in 

        Kivinen J, Warmuth MK. Exponentiated gradient versus gradient 
        descent for linear predictors. Information and computation. 1997;
        132(1):1–63.

    
    '''
    def __init__(self, params, lr=1e-3):
        if lr <= 0.0:
            raise ValueError("Invalid learning rate: {}".format(lr))
        defaults = dict(lr=lr)
        super(ExpGradient, self).__init__(params, defaults)

    def step(self, closure=None):
        '''Performs a single optimization step.
        
        :closure (callable, optional): A closure that reevaluates the model
        	and returns the loss.
        '''
        loss = None
        if closure is not None:
            loss = closure()

        #step_size = self.defaults['lr']
        for group in self.param_groups:
            lr = group['lr']
            for p in group['params']:
                if p.grad is None:
                    continue
                grad = p.grad.data
                if grad.is_sparse:
                    raise RuntimeError('ExpGradient does not support sparse '
                                        +'gradients.')

                state = self.state[p]

                # State initialization
                if len(state) == 0:
                    state['step'] = 0

                state['step'] += 1

                p.data = p.data*torch.exp(- lr * grad)
                p.data = p.data/p.data.sum(0)

        return loss
