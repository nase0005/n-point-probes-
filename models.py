class ExpectedObjectCountNet(nn.Module):
    def __init__(self, probability_map):
        super(ExpectedObjectCountNet, self).__init__()
        self.probability_map = nn.Parameter(probability_map)
        self.K = self.probability_map.shape[0]
        self.H = self.probability_map.shape[1]
        self.W = self.probability_map.shape[2]
        
    def _expected_object_count(self, probes):
        '''
        probes: (B, H, W), B binary probes of size H x W
        '''
        B,H,W = probes.shape
        pseg = self.probability_map #(K, H, W)
        wpseg = torch.einsum('BHW, KHW->BKHW', probes, pseg) # (B, K, H, W)
        prob_seg_not_sampled = 1 - wpseg # (B, K, H, W)
        prob_never_picked = prob_seg_not_sampled.prod(dim=-1).prod(dim=-1) # (B, K)
        expected_object_count = torch.sum(1-prob_never_picked, dim=1) # (B)
        return expected_object_count 

    def forward(self, probes):
        return self._expected_object_count(probes)

    def train(self, probes, count_data, lr=10., laplacian_weight=5., spatial_concentration_weight=1., number_of_epochs=2000, print_progress=False):
        ##instantiate a loss function and optimizer
        from vseg.src.vseg.models import ExpGradient
        optimizer = ExpGradient(self.parameters(), lr=lr)
        criterion = nn.MSELoss(reduction='mean')
        lps = LaplacianSmoothnessLoss()
        var = SpatialConcentrationLoss()

        ##train the network, saving the loss history
        loss_history = []
        for epoch in range(number_of_epochs):
            optimizer.zero_grad()
            pred = self.forward(probes)
            loss = criterion(pred, count_data)
            energy = lps(self.probability_map[np.newaxis,...])
            fogginess = var(self.probability_map[np.newaxis,...])
            total_loss = loss*1. + energy*laplacian_weight + fogginess*spatial_concentration_weight
            loss_history.append(total_loss.item())
            total_loss.backward()
            optimizer.step()
            if print_progress:
                print(f'Epoch {epoch}, loss : {loss.item():.9f}, energy: {energy.item():.9f}, fogginess: {fogginess.item():.9f}')   
        if print_progress:
            print('Done')
        return loss_history

        

